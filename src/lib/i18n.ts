export function translate(lang: Language, key: string) {
  return (
    messages[key]?.[languages.indexOf(lang)] ||
    messages.error[languages.indexOf(lang)]
  );
}
export function detectLanguage(value: string): Language {
  if (/^zh-(TW|HK|MO|Hant)/i.test(value)) return "zh-Hant";
  if (/^zh/i.test(value)) return "zh-Hans";
  if (/^ja/i.test(value)) return "ja";
  if (/^vi/i.test(value)) return "vi";
  return "en";
}
